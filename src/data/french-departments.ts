export const getDepartmentByCode = (
  code: string,
): FrenchDepartment | undefined =>
  FRENCH_DEPARTMENTS.find((d) => d.code === code);

export const getDepartmentBySlug = (
  slug: string,
): FrenchDepartment | undefined =>
  FRENCH_DEPARTMENTS.find((d) => d.slug === slug);

/**
 * Extracts the trailing 2-3 char code from a combined URL segment like
 * "nord-59" or "guadeloupe-971".
 */
export const extractDeptCodeFromUrl = (combined: string): string | null => {
  const match = combined.match(/-(\d{2,3}|2A|2B)$/i);
  return match ? match[1].toUpperCase() : null;
};

/** Builds /clubs-departement/:slug-:code URL path. */
export const departmentUrl = (d: FrenchDepartment): string =>
  `/clubs-departement/${d.slug}-${d.code}`;
